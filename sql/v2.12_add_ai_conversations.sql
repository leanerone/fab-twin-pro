-- v2.12 增量脚本：新增 AI_CONVERSATIONS（T5：session_id → Dify conversation_id 映射持久化）
-- 目标库：Oracle 11g+（XEPDB1 / fabtwin 账号执行）
-- 幂等：重复执行不报错；回退见文件末尾注释
-- ============================================================================
SET DEFINE OFF

-- ---------- 1. 建表 ----------
BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE AI_CONVERSATIONS (
      ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      SESSION_ID    VARCHAR2(64)  NOT NULL,
      USER_ID       NUMBER,
      MACHINE_ID    VARCHAR2(64)  DEFAULT '',
      DIFY_CONV_ID  VARCHAR2(64)  DEFAULT '',
      PROVIDER      VARCHAR2(32)  DEFAULT 'dify',
      CREATED_AT    VARCHAR2(255),
      UPDATED_AT    VARCHAR2(255)
    )
  ]';
  DBMS_OUTPUT.PUT_LINE('AI_CONVERSATIONS created');
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE = -955 THEN
      DBMS_OUTPUT.PUT_LINE('AI_CONVERSATIONS already exists, skipped');
    ELSE
      RAISE;
    END IF;
END;
/

-- ---------- 2. 唯一索引：同一前端会话+机台维度唯一 ----------
BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE UNIQUE INDEX UK_AI_CONV_SESSION
    ON AI_CONVERSATIONS (SESSION_ID, MACHINE_ID)
  ]';
  DBMS_OUTPUT.PUT_LINE('UK_AI_CONV_SESSION created');
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE IN (-955, -1408) THEN
      DBMS_OUTPUT.PUT_LINE('UK_AI_CONV_SESSION already exists, skipped');
    ELSE
      RAISE;
    END IF;
END;
/

-- ---------- 3. 普通索引：按更新时间清理旧会话 ----------
BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE INDEX IDX_AI_CONV_UPDATED
    ON AI_CONVERSATIONS (UPDATED_AT)
  ]';
  DBMS_OUTPUT.PUT_LINE('IDX_AI_CONV_UPDATED created');
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE IN (-955, -1408) THEN
      DBMS_OUTPUT.PUT_LINE('IDX_AI_CONV_UPDATED already exists, skipped');
    ELSE
      RAISE;
    END IF;
END;
/

COMMIT;

